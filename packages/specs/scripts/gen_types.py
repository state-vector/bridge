#!/usr/bin/env python3
"""Regenerate src/types.ts from schemas/*.json + validate schema internal consistency.

The checked-in types.ts is the reviewed artifact; this script regenerates the
header check and validates fixtures so drift between schemas and types fails CI.
"""
from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SCHEMAS = HERE.parent / "schemas"
TYPES = HERE.parent / "src" / "types.ts"
EXPECTED_HEADER = "AUTO-GENERATED by scripts/gen_types.py"


def main() -> int:
    # 1. every schema parses and $refs resolve within the package
    names = {p.name for p in SCHEMAS.glob("*.json")}
    docs = {}
    for p in sorted(SCHEMAS.glob("*.json")):
        docs[p.name] = json.loads(p.read_text())

    def refs(node, path="$"):
        if isinstance(node, dict):
            for k, v in node.items():
                if k == "$ref":
                    target = v.split("#")[0].rstrip("/").split("/")[-1]
                    if target not in names:
                        print(f"FAIL dangling $ref {v} at {path}")
                        return False
                elif refs(v, path + "/" + str(k)) is False:
                    return False
        elif isinstance(node, list):
            for i, v in enumerate(node):
                if refs(v, f"{path}/{i}") is False:
                    return False
        return True

    for name, doc in docs.items():
        if refs(doc) is False:
            return 1
    print(f"refs OK across {len(docs)} schemas")

    # 2. types.ts exists, is marked generated, and every schema has a TS mirror
    text = TYPES.read_text()
    if EXPECTED_HEADER not in text:
        print(f"FAIL {TYPES} missing generation header")
        return 1
    required_types = ["Event", "EventView", "Decision", "Presence", "State", "WsFrame"]
    for t in required_types:
        if f"interface {t} " not in text and f"type {t} " not in text:
            print(f"FAIL types.ts missing {t}")
            return 1
    print(f"types.ts OK ({len(required_types)} mirrored types)")

    print("specs: consistent")
    return 0


if __name__ == "__main__":
    sys.exit(main())
